package tech.beshu.ror.utils;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * Allows a call that the forbidden-apis check rejects, for example a call that uses the JVM default
 * charset. The check reads this annotation from the class files, so it must be a Java annotation.
 */
@Retention(RetentionPolicy.CLASS)
@Target({ElementType.CONSTRUCTOR, ElementType.FIELD, ElementType.METHOD, ElementType.TYPE})
public @interface SuppressForbidden {
  /** Why the call is necessary. */
  String reason();
}
